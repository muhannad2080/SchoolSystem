    public class VoucherService
    {

        private readonly VoucherRepository voucherRepository;
        // تعريف الدالة AuditLogService لتنفيذ العملية المرتبطة بها.
        private readonly AuditLogService auditLogService = new AuditLogService();

        // تعريف الدالة VoucherService لتنفيذ العملية المرتبطة بها.
        public VoucherService()
        {
            voucherRepository = new VoucherRepository();
        }

        // تعريف الدالة GetAllVouchers لتنفيذ العملية المرتبطة بها.
        public DataTable GetAllVouchers()
        {
            // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
            CurrentUser.DemandAction("Vouchers", "View", "ليس لديك صلاحية عرض السندات.");

            return voucherRepository.GetAllVouchers();
        }

        // تعريف الدالة GenerateVoucherNumber لتنفيذ العملية المرتبطة بها.
        public string GenerateVoucherNumber(string voucherType)
        {
            // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
            CurrentUser.DemandAction("Vouchers", "Add", "ليس لديك صلاحية توليد رقم سند.");
            if (voucherType != "قبض" && voucherType != "صرف")

                throw new ArgumentException("نوع السند غير صحيح.", "voucherType");


            return voucherRepository.GenerateVoucherNumber(voucherType);
        }

        // تعريف الدالة AddVoucher لتنفيذ العملية المرتبطة بها.
        public bool AddVoucher(Voucher voucher)
        {
            // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
            CurrentUser.DemandAction("Vouchers", "Add", "ليس لديك صلاحية إضافة السندات.");
            ValidateVoucher(voucher);

            bool added = voucher.VoucherType == "قبض" && voucher.StudentID.HasValue
                ? voucherRepository.AddReceiptVoucherAndPostPayment(voucher)
                : voucherRepository.AddVoucher(voucher);
            if (added)
                auditLogService.Record("إنشاء", "Voucher", voucher.VoucherID.ToString(),
                    string.Format("النوع: {0}، الرقم: {1}، المبلغ: {2}، الطرف: {3}", voucher.VoucherType, voucher.VoucherNumber, voucher.Amount, voucher.PartyName));

            return added;
        }

        // تعريف الدالة UpdateVoucher لتنفيذ العملية المرتبطة بها.
        public bool UpdateVoucher(Voucher voucher)
        {
            // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
            CurrentUser.DemandAction("Vouchers", "Edit", "ليس لديك صلاحية تعديل السندات.");
            if (voucher.VoucherID <= 0)

                throw new Exception("رقم السند غير صحيح.");


            if (voucherRepository.IsAutoGenerated(voucher.VoucherID))

                throw new InvalidOperationException("السند التلقائي للقراءة فقط ولا يمكن تعديله.");

            if (voucherRepository.IsLinkedToStudentFee(voucher.VoucherID))
            {
                Voucher current = voucherRepository.GetVoucherById(voucher.VoucherID);

                if (current == null)

                    throw new InvalidOperationException("تعذر العثور على السند المرتبط بالرسوم.");

                if (current.StudentID.HasValue != voucher.StudentID.HasValue ||
                    current.StudentID.GetValueOrDefault() != voucher.StudentID.GetValueOrDefault() ||
                    !string.Equals((current.ReferenceType ?? string.Empty).Trim(), (voucher.ReferenceType ?? string.Empty).Trim(), StringComparison.OrdinalIgnoreCase) ||
                    current.ReferenceID.GetValueOrDefault() != voucher.ReferenceID.GetValueOrDefault() ||
                    !string.Equals((current.VoucherType ?? string.Empty).Trim(), (voucher.VoucherType ?? string.Empty).Trim(), StringComparison.OrdinalIgnoreCase))
                {
                    throw new InvalidOperationException("سند قبض الطالب المرتبط بالرسوم لا يمكن تغيير نوعه أو مرجعه أو الطالب المرتبط به.");
                }

                if (current.Amount != voucher.Amount)

                    throw new InvalidOperationException("لا يمكن تغيير مبلغ سند قبض الطالب المرتبط بالرسوم بعد تسجيله؛ استخدم سند عكسي ثم أنشئ سنداً جديداً.");
            }

            ValidateVoucher(voucher);

            bool updated = voucherRepository.UpdateVoucher(voucher);
            if (updated)
                auditLogService.Record("تعديل", "Voucher", voucher.VoucherID.ToString(),
                    string.Format("النوع: {0}، المبلغ: {1}، الطرف: {2}", voucher.VoucherType, voucher.Amount, voucher.PartyName));

            return updated;
        }

        // تعريف الدالة DeleteVoucher لتنفيذ العملية المرتبطة بها.
        public bool DeleteVoucher(int voucherId)
        {
            CurrentUser.DemandAction("Vouchers", "Delete", "ليس لديك صلاحية حذف السندات.");
            if (voucherId <= 0)

                throw new Exception("رقم السند غير صحيح.");


            if (voucherRepository.IsAutoGenerated(voucherId))

                throw new InvalidOperationException("السند التلقائي للقراءة فقط ولا يمكن حذفه.");

            if (voucherRepository.IsLinkedToStudentFee(voucherId))

                throw new InvalidOperationException("سند قبض الطالب مرحّل إلى الرسوم ولا يمكن حذفه؛ استخدم سند عكسي أو تسوية مالية.");

            bool deleted = voucherRepository.DeleteVoucher(voucherId);
            if (deleted)
                auditLogService.Record("حذف", "Voucher", voucherId.ToString(), "حذف سند يدوي بعد اجتياز التحقق.");

            return deleted;
        }

        // تعريف الدالة CancelVoucher لإنشاء سند عكسي يلغي الأثر المالي
        // مع إبقاء السند الأصلي كاملاً وحفظ المسار التدقيقي.
        public int CancelVoucher(int voucherId)
        {
            CurrentUser.DemandAction("Vouchers", "Delete", "ليس لديك صلاحية إلغاء السندات.");
            if (voucherId <= 0)

                throw new Exception("رقم السند غير صحيح.");

            int reversalId = voucherRepository.CancelVoucher(voucherId);
            if (reversalId <= 0)

                throw new Exception("تعذر إنشاء السند العكسي للسند المحدد.");

            auditLogService.Record("عكس/إلغاء", "Voucher", voucherId.ToString(),
                "إنشاء سند عكسي لإلغاء الأثر المالي للسند " + voucherId + " دون حذفه.");

            return reversalId;
        }

        public bool CreateReceiptVoucherForFeePayment(
            decimal amount,
            DateTime voucherDate,
            string studentName,
            int feeId,
            string paymentMethod,
            string notes,
            string referenceType = "رسوم")
        {
            Voucher voucher = new Voucher
            {
                VoucherType = "قبض",
                Amount = amount,
                VoucherDate = voucherDate,
                PartyName = studentName,
                Description = "سند قبض رسوم دراسية",
                PaymentMethod = paymentMethod,
                ReferenceType = string.IsNullOrWhiteSpace(referenceType) ? "رسوم" : referenceType.Trim(),
                ReferenceID = feeId,
                Notes = notes,
                IsAutoGenerated = true

            };

            // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
            EnsureCanCreateSystemVoucher(PermissionKeys.FeesManage);

            return AddVoucherCore(voucher, true);
        }

