        // تعريف الدالة AddVoucherCore لتنفيذ العملية المرتبطة بها.
        private bool AddVoucherCore(Voucher voucher, bool forceNew = false)
        {
            ValidateVoucher(voucher);

            bool added = voucherRepository.AddVoucher(voucher, forceNew);
            if (added)
                auditLogService.Record("إنشاء", "Voucher", voucher.VoucherID.ToString(),
                    string.Format("سند تلقائي؛ النوع: {0}، الرقم: {1}، المبلغ: {2}، الطرف: {3}", voucher.VoucherType, voucher.VoucherNumber, voucher.Amount, voucher.PartyName));

            return added;
        }

        // تعريف الدالة EnsureCanCreateSystemVoucher لتنفيذ العملية المرتبطة بها.
        private static void EnsureCanCreateSystemVoucher(string owningPermission)
        {
            // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
            bool canCreate = CurrentUser.CanAdd("Vouchers") || CurrentUser.HasPermission(PermissionKeys.VouchersManage);
            if (owningPermission == PermissionKeys.FeesManage)
                // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
                canCreate = canCreate || CurrentUser.CanAdd("Fees") || CurrentUser.HasPermission(PermissionKeys.FeesManage);

            else if (owningPermission == PermissionKeys.ExpensesManage)
                // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
                canCreate = canCreate || CurrentUser.CanAdd("Expenses") || CurrentUser.HasPermission(PermissionKeys.ExpensesManage);

            else if (owningPermission == PermissionKeys.PayrollManage)
                // التأكد من أن الجلسة تملك الصلاحية اللازمة للعملية.
                canCreate = canCreate || CurrentUser.CanAdd("Payroll") || CurrentUser.HasPermission(PermissionKeys.PayrollManage);

            if (!canCreate)

                throw new UnauthorizedAccessException("ليس لديك صلاحية إنشاء السند التلقائي المرتبط بهذه العملية.");
        }

        // تعريف الدالة ValidateVoucher لتنفيذ العملية المرتبطة بها.
        private void ValidateVoucher(Voucher voucher)
        {
            if (voucher == null)

                throw new Exception("بيانات السند غير موجودة.");


            if (voucher.VoucherType != "قبض" && voucher.VoucherType != "صرف")

                throw new Exception("نوع السند يجب أن يكون قبض أو صرف.");


            if (voucher.Amount <= 0)

                throw new Exception("مبلغ السند يجب أن يكون أكبر من صفر.");


            if (string.IsNullOrWhiteSpace(voucher.PartyName))

                throw new Exception("يرجى إدخال اسم الطرف.");


            if (voucher.StudentID.HasValue && voucher.StudentID.Value <= 0)

                throw new Exception("هوية الطالب غير صحيحة.");


            if (!voucher.IsAutoGenerated && voucher.VoucherType == "قبض")
            {
                if (!string.Equals(voucher.PartyType, "طلاب", StringComparison.OrdinalIgnoreCase) || !voucher.StudentID.HasValue)

                    throw new Exception("سند القبض اليدوي مخصص للطلاب فقط؛ اختر طالباً من قائمة الطرف.");
            }

            if (!voucher.IsAutoGenerated && voucher.VoucherType == "صرف")
            {
                if (voucher.StudentID.HasValue ||
                    (voucher.PartyType != "معلمون" && voucher.PartyType != "موظفون"))

                    throw new Exception("سند الصرف اليدوي مخصص للمعلمين والموظفين فقط؛ اختر المستفيد المالي الصحيح.");
            }

            if (voucher.VoucherType == "قبض" && voucher.StudentID.HasValue)
            {
                voucher.ReferenceType = "رسوم";
                if (voucher.IsAutoGenerated)

                    throw new Exception("سند قبض الطالب من الشاشة اليدوية يجب أن يكون غير تلقائي.");
            }

            if (string.IsNullOrWhiteSpace(voucher.Description))

                throw new Exception("يرجى إدخال البيان.");


            if (voucher.VoucherDate.Date > DateTime.Today)

                throw new Exception("تاريخ السند لا يمكن أن يكون في المستقبل.");


            if (string.IsNullOrWhiteSpace(voucher.PaymentMethod))

                throw new Exception("يرجى تحديد طريقة الدفع.");

            bool hasReference = voucher.ReferenceID.HasValue && voucher.ReferenceID.Value > 0;
            bool isGeneralReference = string.IsNullOrWhiteSpace(voucher.ReferenceType) || voucher.ReferenceType == "عام";
            if (!isGeneralReference && !hasReference)

                throw new Exception("رقم المرجع مطلوب عند اختيار نوع مرجع مرتبط.");

            if (isGeneralReference && hasReference)

                throw new Exception("لا يمكن استخدام رقم مرجع مع النوع العام.");

            if (voucher.ReferenceID.HasValue && voucher.ReferenceID.Value <= 0)

                throw new Exception("رقم المرجع يجب أن يكون موجبًا.");
        }
