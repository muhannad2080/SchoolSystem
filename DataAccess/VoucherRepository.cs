        // تعريف الدالة AddVoucher لتنفيذ العملية المرتبطة بها.
        public bool AddVoucher(Voucher voucher, bool forceNew = false)
        {


            bool needsGeneratedNumber = string.IsNullOrWhiteSpace(voucher.VoucherNumber) ||
                IsGeneratedVoucherNumber(voucher.VoucherNumber, voucher.VoucherType);
            if (needsGeneratedNumber)
                voucher.VoucherNumber = null;

            using (SqlConnection con = DbConnection.GetConnection())
            {
                string query = @"
                    IF @VoucherNumber IS NOT NULL AND EXISTS
                    (
                        SELECT 1 FROM Vouchers WITH (UPDLOCK, HOLDLOCK)
                        WHERE VoucherNumber = @VoucherNumber
                    )
                        THROW 51007, N'رقم السند مستخدم مسبقًا؛ أعد توليد الرقم ثم حاول مرة أخرى.', 1;

                    IF @IsAutoGenerated = 1 AND @ForceNew = 0 AND @ReferenceID IS NOT NULL AND EXISTS
                    (
                        SELECT 1 FROM Vouchers WITH (UPDLOCK, HOLDLOCK)
                        WHERE IsAutoGenerated = 1
                          AND VoucherType = @VoucherType
                          AND ReferenceType = @ReferenceType
                          AND ReferenceID = @ReferenceID
                    )
                    BEGIN
                        /*
                           الإنشاء التلقائي idempotent: إعادة فتح الشاشة أو إعادة الإنشاء
                           يجب ألا تكرر السند المرتبط بالمستند الواحد؛ نعيد السند الموجود
                           دون إعادة بناء رقمه حتى لا يتغير الرقم مع تغير التاريخ.
                        */
                        SELECT TOP 1 VoucherID, VoucherNumber
                        FROM Vouchers WITH (UPDLOCK, HOLDLOCK)
                        WHERE IsAutoGenerated = 1
                          AND VoucherType = @VoucherType
                          AND ReferenceType = @ReferenceType
                          AND ReferenceID = @ReferenceID
                        ORDER BY VoucherID DESC;
                        RETURN;
                    END;

                    INSERT INTO Vouchers
                    (
                        VoucherNumber,
                        VoucherType,
                        Amount,
                        VoucherDate,
                        PartyName,
                        Description,
                        PaymentMethod,
                        ReferenceType,
                        ReferenceID,
                        Notes,
                        IsAutoGenerated
                    )
                    VALUES
                    (
                        @VoucherNumber,
                        @VoucherType,
                        @Amount,
                        @VoucherDate,
                        @PartyName,
                        @Description,
                        @PaymentMethod,
                        @ReferenceType,
                        @ReferenceID,
                        @Notes,
                        @IsAutoGenerated
                    );
                    SELECT CAST(SCOPE_IDENTITY() AS INT);";


                using (SqlCommand cmd = new SqlCommand(query, con))
                {
                    AddParameters(cmd, voucher, forceNew);


                    con.Open();

                    using (SqlTransaction transaction = con.BeginTransaction(IsolationLevel.Serializable))
                    {
                        cmd.Transaction = transaction;

                        using (SqlDataReader reader = cmd.ExecuteReader())
                        {
                            if (reader.FieldCount >= 2 && reader.Read())
                            {
                                /* فرع idempotent: يوجد سند تلقائي لنفس المرجع، نعيد بياناته كما هي دون ترقيم جديد. */
                                voucher.VoucherID = Convert.ToInt32(reader["VoucherID"]);

                                if (reader["VoucherNumber"] != DBNull.Value)
                                    voucher.VoucherNumber = Convert.ToString(reader["VoucherNumber"]);

                                reader.Close();
                                transaction.Commit();

                                return voucher.VoucherID > 0;
                            }

                            if (!reader.Read())
                            {
                                reader.Close();
                                transaction.Rollback();

                                return false;
                            }

                            voucher.VoucherID = Convert.ToInt32(reader[0]);
                            reader.Close();
                        }

                        if (needsGeneratedNumber)
                        {
                            voucher.VoucherNumber = BuildVoucherNumber(voucher.VoucherType, voucher.VoucherDate, voucher.VoucherID);
                            using (SqlCommand numberCommand = new SqlCommand(
                                "UPDATE Vouchers SET VoucherNumber = @VoucherNumber WHERE VoucherID = @VoucherID", con, transaction))
                            {

                                numberCommand.Parameters.AddWithValue("@VoucherNumber", voucher.VoucherNumber);

                                numberCommand.Parameters.AddWithValue("@VoucherID", voucher.VoucherID);

                                numberCommand.ExecuteNonQuery();
                            }
                        }

                        transaction.Commit();

                        return voucher.VoucherID > 0;
                    }
                }
            }
        }

        // تعريف الدالة AddReceiptVoucherAndPostPayment لتنفيذ العملية المرتبطة بها.
        public bool AddReceiptVoucherAndPostPayment(Voucher voucher)
        {
            if (voucher == null || !voucher.StudentID.HasValue)

                throw new ArgumentException("سند قبض الطالب يحتاج إلى هوية طالب صحيحة.", "voucher");

            bool needsGeneratedNumber = string.IsNullOrWhiteSpace(voucher.VoucherNumber) ||
                IsGeneratedVoucherNumber(voucher.VoucherNumber, voucher.VoucherType);
            using (SqlConnection con = DbConnection.GetConnection())
            using (SqlCommand cmd = new SqlCommand(@"
                SET NOCOUNT ON;
                SET XACT_ABORT ON;
                DECLARE @StudentID INT = @InputStudentID;
                DECLARE @AcademicYear NVARCHAR(100);
                DECLARE @FeeID INT;
                DECLARE @CurrentFeeID INT;
                DECLARE @CurrentRemaining DECIMAL(18,2);
                DECLARE @AppliedAmount DECIMAL(18,2);
                DECLARE @RemainingPayment DECIMAL(18,2) = @Amount;
                DECLARE @VoucherID INT;
                DECLARE @TotalFeeID INT;
                DECLARE @TotalPaid DECIMAL(18,2);
                DECLARE @TotalNet DECIMAL(18,2);
                DECLARE @GeneratedVoucherNumber NVARCHAR(100);

                IF NOT EXISTS (SELECT 1 FROM dbo.Students WHERE StudentID = @StudentID)
                    THROW 51045, N'الطالب المحدد غير موجود.', 1;

                SELECT TOP 1 @AcademicYear = NULLIF(LTRIM(RTRIM(e.AcademicYear)), N'')
                FROM dbo.Enrollments e WITH (UPDLOCK, HOLDLOCK)
                WHERE e.StudentID = @StudentID
                ORDER BY e.EnrollmentID DESC;

                IF NULLIF(@AcademicYear, N'') IS NULL
                    SELECT TOP 1 @AcademicYear = NULLIF(LTRIM(RTRIM(f.AcademicYear)), N'')
                    FROM dbo.Fees f WITH (UPDLOCK, HOLDLOCK)
                    WHERE f.StudentID = @StudentID
                    ORDER BY f.FeeID DESC;

                IF NULLIF(@AcademicYear, N'') IS NULL
                    THROW 51046, N'لا توجد سنة دراسية مرتبطة بتسجيل الطالب أو رسومه.', 1;

                SELECT TOP 1 @FeeID = f.FeeID
                FROM dbo.Fees f WITH (UPDLOCK, HOLDLOCK)
                WHERE f.StudentID = @StudentID
                  AND REPLACE(ISNULL(f.AcademicYear, N''), N'-', N'/') = REPLACE(@AcademicYear, N'-', N'/')
                  AND LTRIM(RTRIM(ISNULL(f.FeeType, N''))) NOT IN
                      (N'الرسوم الكلية', N'رسوم كلية', N'الرسوم الكليه', N'رسوم كليه', N'Total Fee')
                ORDER BY f.FeeID;

                IF @FeeID IS NULL
                    THROW 51047, N'لا توجد رسوم لهذا الطالب في السنة الدراسية المرتبطة.', 1;

                IF @VoucherNumber IS NOT NULL AND EXISTS
                (
                    SELECT 1 FROM dbo.Vouchers WITH (UPDLOCK, HOLDLOCK)
                    WHERE VoucherNumber = @VoucherNumber
                )
                    THROW 51007, N'رقم السند مستخدم مسبقاً؛ أعد المحاولة لتوليد رقم جديد.', 1;

                SET @GeneratedVoucherNumber = @VoucherNumber;

                INSERT INTO dbo.Vouchers
                (VoucherNumber, VoucherType, Amount, VoucherDate, PartyName, Description,
                 PaymentMethod, ReferenceType, ReferenceID, Notes, IsAutoGenerated)
                VALUES
                (@GeneratedVoucherNumber, N'قبض', @Amount, @VoucherDate, @PartyName, @Description,
                 @PaymentMethod, N'رسوم', @FeeID, @Notes, 0);

                SET @VoucherID = CONVERT(INT, SCOPE_IDENTITY());

                IF NULLIF(@GeneratedVoucherNumber, N'') IS NULL
                    SET @GeneratedVoucherNumber =
                        N'REC-' + CONVERT(NVARCHAR(4), YEAR(@VoucherDate)) +
                        N'-' + RIGHT(N'00000' + CONVERT(NVARCHAR(20), @VoucherID), 5);

                UPDATE dbo.Vouchers
                SET VoucherNumber = @GeneratedVoucherNumber
                WHERE VoucherID = @VoucherID;

                WHILE @RemainingPayment > 0
                BEGIN
                    SET @CurrentFeeID = NULL;
                    SELECT TOP 1 @CurrentFeeID = f.FeeID, @CurrentRemaining = ISNULL(f.RemainingAmount, 0)
                    FROM dbo.Fees f WITH (UPDLOCK, HOLDLOCK)
                    WHERE f.StudentID = @StudentID
                      AND REPLACE(ISNULL(f.AcademicYear, N''), N'-', N'/') = REPLACE(@AcademicYear, N'-', N'/')
                      AND ISNULL(f.RemainingAmount, 0) > 0
                      AND LTRIM(RTRIM(ISNULL(f.FeeType, N''))) NOT IN
                          (N'الرسوم الكلية', N'رسوم كلية', N'الرسوم الكليه', N'رسوم كليه', N'Total Fee')
                    ORDER BY CASE WHEN f.FeeID = @FeeID THEN 0 ELSE 1 END, f.FeeID;

                    IF @CurrentFeeID IS NULL BREAK;

                    SET @AppliedAmount = CASE WHEN @RemainingPayment < @CurrentRemaining
                                               THEN @RemainingPayment ELSE @CurrentRemaining END;
                    UPDATE dbo.Fees
                    SET PaidAmount = ISNULL(PaidAmount, 0) + @AppliedAmount,
                        RemainingAmount = ISNULL(RemainingAmount, 0) - @AppliedAmount,
                        PaymentDate = @VoucherDate,
                        PaymentMethod = @PaymentMethod,
                        ReceiptNumber = @GeneratedVoucherNumber,
                        Notes = CASE WHEN NULLIF(@Notes, N'') IS NULL THEN Notes
                                     WHEN NULLIF(Notes, N'') IS NULL THEN @Notes
                                     ELSE LEFT(Notes + N' | دفعة سند: ' + @VoucherNumber, 500) END,
                        Status = CASE WHEN ISNULL(RemainingAmount, 0) - @AppliedAmount <= 0
                                      THEN N'مسدد' ELSE N'مسدد جزئياً' END,
                        UpdatedAt = GETDATE()
                    WHERE FeeID = @CurrentFeeID;
                    SET @RemainingPayment = @RemainingPayment - @AppliedAmount;
                END;

                IF @RemainingPayment > 0
                BEGIN
                    DECLARE @CreditFeeID INT;

                    SELECT TOP (1) @CreditFeeID = f.FeeID
                    FROM dbo.Fees f WITH (UPDLOCK, HOLDLOCK)
                    WHERE f.StudentID = @StudentID
                      AND REPLACE(ISNULL(f.AcademicYear, N''), N'-', N'/') = REPLACE(@AcademicYear, N'-', N'/')
                      AND LTRIM(RTRIM(ISNULL(f.FeeType, N''))) NOT IN
                          (N'الرسوم الكلية', N'رسوم كلية', N'الرسوم الكليه', N'رسوم كليه', N'Total Fee')
                    ORDER BY f.FeeID;

                    IF @CreditFeeID IS NULL
                        THROW 51055, N'لا توجد بنود رسوم فعلية لترحيل الدفعة الزائدة كرَصيد دائن.', 1;

                    UPDATE dbo.Fees
                    SET PaidAmount = ISNULL(PaidAmount, 0) + @RemainingPayment,
                        RemainingAmount = ISNULL(RemainingAmount, 0) - @RemainingPayment,
                        PaymentDate = @VoucherDate,
                        PaymentMethod = @PaymentMethod,
                        ReceiptNumber = @GeneratedVoucherNumber,
                        Notes = CASE WHEN NULLIF(@Notes, N'') IS NULL THEN Notes
                                     WHEN NULLIF(Notes, N'') IS NULL THEN @Notes
                                     ELSE LEFT(Notes + N' | رصيد دائن من سند: ' + @GeneratedVoucherNumber, 500) END,
                        Status = N'رصيد دائن',
                        UpdatedAt = GETDATE()
                    WHERE FeeID = @CreditFeeID;

                    SET @RemainingPayment = 0;
                END;

                /* مزامنة الرسوم الكلية من بنود الرسوم الفعلية فقط. */
                SELECT TOP (1) @TotalFeeID = f.FeeID
                FROM dbo.Fees f WITH (UPDLOCK, HOLDLOCK)
                WHERE f.StudentID = @StudentID
                  AND REPLACE(ISNULL(f.AcademicYear, N''), N'-', N'/') = REPLACE(@AcademicYear, N'-', N'/')
                  AND LTRIM(RTRIM(ISNULL(f.FeeType, N''))) IN
                      (N'الرسوم الكلية', N'رسوم كلية', N'الرسوم الكليه', N'رسوم كليه', N'Total Fee')
                ORDER BY f.FeeID;

                IF @TotalFeeID IS NOT NULL
                BEGIN
                    SELECT @TotalPaid = ISNULL(SUM(f.PaidAmount), 0)
                    FROM dbo.Fees f WITH (UPDLOCK, HOLDLOCK)
                    WHERE f.StudentID = @StudentID
                      AND REPLACE(ISNULL(f.AcademicYear, N''), N'-', N'/') = REPLACE(@AcademicYear, N'-', N'/')
                      AND LTRIM(RTRIM(ISNULL(f.FeeType, N''))) NOT IN
                          (N'الرسوم الكلية', N'رسوم كلية', N'الرسوم الكليه', N'رسوم كليه', N'Total Fee');

                    SELECT @TotalNet = ISNULL(NetAmount, 0)
                    FROM dbo.Fees WITH (UPDLOCK, HOLDLOCK)
                    WHERE FeeID = @TotalFeeID;

                    UPDATE dbo.Fees
                    SET PaidAmount = @TotalPaid,
                        RemainingAmount = @TotalNet - @TotalPaid,
                        Status = CASE
                            WHEN @TotalNet - @TotalPaid < 0 THEN N'رصيد دائن'
                            WHEN @TotalNet - @TotalPaid <= 0 THEN N'مسدد'
                            WHEN @TotalPaid > 0 THEN N'مسدد جزئياً'
                            ELSE N'غير مسدد'
                        END,
                        UpdatedAt = GETDATE()
                    WHERE FeeID = @TotalFeeID;
                END;

                SELECT @VoucherID AS VoucherID,
                       @FeeID AS ReferenceID,
                       @GeneratedVoucherNumber AS VoucherNumber;
", con))
            {

                cmd.Parameters.AddWithValue("@InputStudentID", voucher.StudentID.Value);

                cmd.Parameters.AddWithValue("@VoucherNumber", needsGeneratedNumber ? (object)DBNull.Value : voucher.VoucherNumber.Trim());

                cmd.Parameters.AddWithValue("@Amount", voucher.Amount);

                cmd.Parameters.AddWithValue("@VoucherDate", voucher.VoucherDate.Date);

                cmd.Parameters.AddWithValue("@PartyName", voucher.PartyName ?? string.Empty);

                cmd.Parameters.AddWithValue("@Description", voucher.Description ?? string.Empty);

                cmd.Parameters.AddWithValue("@PaymentMethod", voucher.PaymentMethod ?? string.Empty);

                cmd.Parameters.AddWithValue("@Notes", voucher.Notes ?? string.Empty);

                con.Open();

                using (SqlTransaction transaction = con.BeginTransaction(IsolationLevel.Serializable))
                {
                    cmd.Transaction = transaction;
                    using (SqlDataReader reader = cmd.ExecuteReader())
                    {
                        if (!reader.Read())
                            throw new InvalidOperationException("تعذر إنشاء سند القبض.");

                        voucher.VoucherID = reader.GetInt32(0);
                        voucher.ReferenceID = reader.GetInt32(1);
                        voucher.ReferenceType = "رسوم";

                        if (reader.FieldCount >= 3 && !reader.IsDBNull(2))
                            voucher.VoucherNumber = reader.GetString(2);

                    transaction.Commit();

                    return voucher.VoucherID > 0;
                }
            }
        }

        // تعريف الدالة UpdateVoucher لتنفيذ العملية المرتبطة بها.
        public bool UpdateVoucher(Voucher voucher)
        {
            using (SqlConnection con = DbConnection.GetConnection())
            {
                const string query = @"
                    IF EXISTS
                    (
                        SELECT 1
                        FROM Vouchers
                        WHERE VoucherID = @VoucherID
                          AND IsAutoGenerated = 1
                    )
                    BEGIN
                        THROW 51006, N'لا يمكن تعديل السند المنشأ تلقائياً لأنه جزء من التسوية المالية.', 1;
                    END;

                    IF @VoucherNumber IS NOT NULL AND EXISTS
                    (
                        SELECT 1
                        FROM Vouchers
                        WHERE VoucherNumber = @VoucherNumber
                          AND VoucherID <> @VoucherID
                    )
                        THROW 51008, N'رقم السند مستخدم مسبقاً لسند آخر؛ اختر رقماً مختلفاً.', 1;

                    UPDATE Vouchers SET
                        VoucherNumber = @VoucherNumber,
                        VoucherType = @VoucherType,
                        Amount = @Amount,
                        VoucherDate = @VoucherDate,
                        PartyName = @PartyName,
                        Description = @Description,
                        PaymentMethod = @PaymentMethod,
                        ReferenceType = @ReferenceType,
                        ReferenceID = @ReferenceID,
                        Notes = @Notes,
                        IsAutoGenerated = @IsAutoGenerated
                    WHERE VoucherID = @VoucherID
                      AND IsAutoGenerated = 0;";

                using (SqlCommand cmd = new SqlCommand(query, con))
                {

                    cmd.Parameters.AddWithValue("@VoucherID", voucher.VoucherID);

                    AddParameters(cmd, voucher);


                    con.Open();

                    return cmd.ExecuteNonQuery() > 0;
                }
            }
        }

