        // تعريف الدالة CancelVoucher لإنشاء سند عكسي يلغي الأثر المالي
        // مع إبقاء السند الأصلي كاملاً وحفظ المسار التدقيقي دون كسر العلاقات.
        public int CancelVoucher(int voucherId)
        {
            const string query = @"
                SET NOCOUNT ON;
                SET XACT_ABORT ON;

                DECLARE @OriginalID INT = @VoucherID;
                DECLARE @OriginalNotes NVARCHAR(MAX);
                DECLARE @OriginalNumber NVARCHAR(50);
                DECLARE @OriginalType NVARCHAR(30);
                DECLARE @OriginalAmount DECIMAL(18,2);
                DECLARE @OriginalDate DATE;
                DECLARE @OriginalParty NVARCHAR(200);
                DECLARE @OriginalPayMethod NVARCHAR(50);
                DECLARE @OriginalRefType NVARCHAR(50);
                DECLARE @OriginalRefID INT;
                DECLARE @OriginalStudentID INT = NULL;
                DECLARE @OriginalAcademicYear NVARCHAR(100) = NULL;
                DECLARE @ReverseType NVARCHAR(30);
                DECLARE @NewVoucherID INT;
                DECLARE @NewVoucherNumber NVARCHAR(50);
                DECLARE @RemainingReversal DECIMAL(18,2);
                DECLARE @CurrentFeeID INT;
                DECLARE @CurrentPaid DECIMAL(18,2);
                DECLARE @AppliedAmount DECIMAL(18,2);

                IF NOT EXISTS (SELECT 1 FROM dbo.Vouchers WHERE VoucherID = @OriginalID)
                    THROW 51009, N'السند المحدد غير موجود.', 1;

                SELECT @OriginalNotes = Notes,
                       @OriginalNumber = VoucherNumber,
                       @OriginalType = VoucherType,
                       @OriginalAmount = Amount,
                       @OriginalDate = VoucherDate,
                       @OriginalParty = PartyName,
                       @OriginalPayMethod = PaymentMethod,
                       @OriginalRefType = ReferenceType,
                       @OriginalRefID = ReferenceID
                FROM dbo.Vouchers WITH (UPDLOCK, HOLDLOCK)
                WHERE VoucherID = @OriginalID;

                IF @OriginalRefType = N'رسوم' AND @OriginalRefID IS NOT NULL
                BEGIN
                    SELECT @OriginalStudentID = StudentID, @OriginalAcademicYear = AcademicYear
                    FROM dbo.Fees WITH (UPDLOCK, HOLDLOCK)
                    WHERE FeeID = @OriginalRefID;
                END;

                IF ISNULL(CONVERT(NVARCHAR(MAX), @OriginalNotes), N'') LIKE N'%| أُلغي بسند عكسي%'
                    THROW 51010, N'تم إلغاء هذا السند مسبقاً بسند عكسي.', 1;

                IF @OriginalRefType = N'رسوم' AND @OriginalRefID IS NOT NULL AND @OriginalStudentID IS NOT NULL AND @OriginalType = N'قبض'
                BEGIN
                    SET @RemainingReversal = @OriginalAmount;

                    WHILE @RemainingReversal > 0
                    BEGIN
                        SET @CurrentFeeID = NULL;

                        SELECT TOP 1
                            @CurrentFeeID = f.FeeID,
                            @CurrentPaid = ISNULL(f.PaidAmount, 0)
                        FROM dbo.Fees f WITH (UPDLOCK, HOLDLOCK)
                        WHERE f.StudentID = @OriginalStudentID
                          AND REPLACE(ISNULL(f.AcademicYear, N''), N'-', N'/') = REPLACE(ISNULL(@OriginalAcademicYear, N''), N'-', N'/')
                          AND ISNULL(f.PaidAmount, 0) > 0
                        ORDER BY CASE WHEN f.FeeID = @OriginalRefID THEN 0 ELSE 1 END, f.FeeID;

                        IF @CurrentFeeID IS NULL BREAK;

                        SET @AppliedAmount = CASE WHEN @RemainingReversal < @CurrentPaid THEN @RemainingReversal ELSE @CurrentPaid END;

                        UPDATE dbo.Fees
                        SET PaidAmount = ISNULL(PaidAmount, 0) - @AppliedAmount,
                            RemainingAmount = ISNULL(RemainingAmount, 0) + @AppliedAmount,
                            PaymentDate = CASE WHEN ISNULL(PaidAmount, 0) - @AppliedAmount <= 0 THEN NULL ELSE PaymentDate END,
                            PaymentMethod = CASE WHEN ISNULL(PaidAmount, 0) - @AppliedAmount <= 0 THEN NULL ELSE PaymentMethod END,
                            ReceiptNumber = CASE WHEN ISNULL(PaidAmount, 0) - @AppliedAmount <= 0 THEN NULL ELSE ReceiptNumber END,
                            Status = CASE
                                WHEN ISNULL(PaidAmount, 0) - @AppliedAmount <= 0 THEN
                                    CASE WHEN DueDate < CONVERT(date, GETDATE()) THEN N'متأخر' ELSE N'غير مسدد' END
                                WHEN ISNULL(RemainingAmount, 0) + @AppliedAmount <= 0 THEN N'مسدد'
                                ELSE N'مسدد جزئياً'
                            END,
                            UpdatedAt = GETDATE()
                        WHERE FeeID = @CurrentFeeID;

                        SET @RemainingReversal = @RemainingReversal - @AppliedAmount;
                    END;
                END;

                SET @ReverseType = CASE WHEN @OriginalType = N'قبض' THEN N'صرف' ELSE N'قبض' END;

                INSERT INTO dbo.Vouchers
                (VoucherNumber, VoucherType, Amount, VoucherDate, PartyName, Description,
                 PaymentMethod, ReferenceType, ReferenceID, Notes, IsAutoGenerated)
                VALUES
                (NULL, @ReverseType, @OriginalAmount, @OriginalDate,
                 @OriginalParty + N' (عكسي)',
                 N'سند عكسي للسند الأصلي ' + ISNULL(@OriginalNumber, CONVERT(NVARCHAR(20), @OriginalID)),
                 @OriginalPayMethod, @OriginalRefType, @OriginalRefID,
                 N'سند عكسي؛ إلغاء الأثر المالي للسند رقم ' + CONVERT(NVARCHAR(20), @OriginalID), 1);

                SET @NewVoucherID = CONVERT(INT, SCOPE_IDENTITY());

                SET @NewVoucherNumber =
                    (CASE WHEN @ReverseType = N'صرف' THEN N'PAY-' ELSE N'REC-' END)
                    + CONVERT(NVARCHAR(4), YEAR(@OriginalDate)) + N'-'
                    + RIGHT(N'00000' + CONVERT(NVARCHAR(10), @NewVoucherID), 5);

                UPDATE dbo.Vouchers SET VoucherNumber = @NewVoucherNumber WHERE VoucherID = @NewVoucherID;

                UPDATE dbo.Vouchers
                SET Notes = LEFT(ISNULL(CONVERT(NVARCHAR(MAX), Notes), N'') + N' | أُلغي بسند عكسي ' + @NewVoucherNumber, 495)
                WHERE VoucherID = @OriginalID;

                SELECT @NewVoucherID AS NewVoucherID, @NewVoucherNumber AS NewVoucherNumber;";

            using (SqlConnection con = DbConnection.GetConnection())
            using (SqlCommand cmd = new SqlCommand(query, con))
            {
                cmd.Parameters.AddWithValue("@VoucherID", voucherId);

                con.Open();

                using (SqlTransaction transaction = con.BeginTransaction(IsolationLevel.Serializable))
                {
                    cmd.Transaction = transaction;

                    using (SqlDataReader reader = cmd.ExecuteReader())
                    {
                        if (!reader.Read())
                        {
                            reader.Close();
                            transaction.Rollback();

                            return 0;
                        }

                        int newVoucherId = Convert.ToInt32(reader["NewVoucherID"]);

                        reader.Close();
                        transaction.Commit();

                        return newVoucherId;
                    }
                }
            }
        }

        // تعريف الدالة BuildVoucherNumber لتنفيذ العملية المرتبطة بها.
        private string BuildVoucherNumber(string voucherType, DateTime voucherDate, int voucherId)
        {
            string prefix = voucherType == "صرف" ? "PAY" : "REC";

            return prefix + "-" + voucherDate.Year + "-" + voucherId.ToString("00000");
        }

        // تعريف الدالة IsGeneratedVoucherNumber لتنفيذ العملية المرتبطة بها.
        private bool IsGeneratedVoucherNumber(string voucherNumber, string voucherType)
        {
            if (string.IsNullOrWhiteSpace(voucherNumber))
                return false;

            string prefix = voucherType == "صرف" ? "PAY-" : "REC-";

            return voucherNumber.Trim().StartsWith(prefix, StringComparison.OrdinalIgnoreCase);
        }

        // تعريف الدالة GenerateVoucherNumber لتنفيذ العملية المرتبطة بها.
        public string GenerateVoucherNumber(string voucherType)
        {
            string prefix = voucherType == "صرف" ? "PAY" : "REC";

            using (SqlConnection con = DbConnection.GetConnection())
            {
                string query = "SELECT ISNULL(MAX(VoucherID), 0) + 1 FROM Vouchers";

                using (SqlCommand cmd = new SqlCommand(query, con))
                {

                    con.Open();


                    int nextNumber = Convert.ToInt32(cmd.ExecuteScalar());


                    return prefix + "-" + DateTime.Today.Year + "-" + nextNumber.ToString("00000");
                }
            }
        }

        // تعريف الدالة AddParameters لتنفيذ العملية المرتبطة بها.
        private void AddParameters(SqlCommand cmd, Voucher voucher, bool forceNew = false)
        {

            cmd.Parameters.AddWithValue(

                "@VoucherNumber",
                string.IsNullOrWhiteSpace(voucher.VoucherNumber)
                    ? (object)DBNull.Value
                    : voucher.VoucherNumber.Trim());

            cmd.Parameters.AddWithValue("@VoucherType", voucher.VoucherType ?? "");

            cmd.Parameters.AddWithValue("@Amount", voucher.Amount);

            cmd.Parameters.AddWithValue("@VoucherDate", voucher.VoucherDate.Date);

            cmd.Parameters.AddWithValue("@PartyName", voucher.PartyName ?? "");

            cmd.Parameters.AddWithValue("@Description", voucher.Description ?? "");


            cmd.Parameters.AddWithValue(

                "@PaymentMethod",
                string.IsNullOrWhiteSpace(voucher.PaymentMethod)
                    ? (object)DBNull.Value
                    : voucher.PaymentMethod
            );


            cmd.Parameters.AddWithValue(

                "@ReferenceType",
                string.IsNullOrWhiteSpace(voucher.ReferenceType)
                    ? (object)DBNull.Value
                    : voucher.ReferenceType
            );

            if (voucher.ReferenceID.HasValue)
                cmd.Parameters.AddWithValue("@ReferenceID", voucher.ReferenceID.Value);

            else

                cmd.Parameters.AddWithValue("@ReferenceID", DBNull.Value);


            cmd.Parameters.AddWithValue(

                "@Notes",
                string.IsNullOrWhiteSpace(voucher.Notes)
                    ? (object)DBNull.Value
                    : voucher.Notes
            );


            cmd.Parameters.AddWithValue("@IsAutoGenerated", voucher.IsAutoGenerated);

            cmd.Parameters.AddWithValue("@ForceNew", forceNew);
        }
