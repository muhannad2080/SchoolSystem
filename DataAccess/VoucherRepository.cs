        // تعريف الدالة GetVoucherById لتنفيذ العملية المرتبطة بها.
        public Voucher GetVoucherById(int voucherId)
        {
            using (SqlConnection con = DbConnection.GetConnection())
            using (SqlCommand cmd = new SqlCommand(@"
                SELECT TOP 1
                    VoucherID, VoucherNumber, VoucherType, Amount, VoucherDate,
                    PartyName, Description, PaymentMethod, ReferenceType, ReferenceID,
                    Notes, IsAutoGenerated, CreatedAt
                FROM dbo.Vouchers
                WHERE VoucherID = @VoucherID", con))
            {
                cmd.Parameters.AddWithValue("@VoucherID", voucherId);

                con.Open();

                using (SqlDataReader reader = cmd.ExecuteReader())
                {
                    if (!reader.Read())
                        return null;

                    return new Voucher
                    {
                        VoucherID = Convert.ToInt32(reader["VoucherID"]),
                        VoucherNumber = reader["VoucherNumber"] == DBNull.Value ? string.Empty : reader["VoucherNumber"].ToString(),
                        VoucherType = reader["VoucherType"] == DBNull.Value ? string.Empty : reader["VoucherType"].ToString(),
                        Amount = reader["Amount"] == DBNull.Value ? 0m : Convert.ToDecimal(reader["Amount"]),
                        VoucherDate = reader["VoucherDate"] == DBNull.Value ? DateTime.MinValue : Convert.ToDateTime(reader["VoucherDate"]),
                        PartyName = reader["PartyName"] == DBNull.Value ? string.Empty : reader["PartyName"].ToString(),
                        Description = reader["Description"] == DBNull.Value ? string.Empty : reader["Description"].ToString(),
                        PaymentMethod = reader["PaymentMethod"] == DBNull.Value ? string.Empty : reader["PaymentMethod"].ToString(),
                        ReferenceType = reader["ReferenceType"] == DBNull.Value ? string.Empty : reader["ReferenceType"].ToString(),
                        ReferenceID = reader["ReferenceID"] == DBNull.Value ? (int?)null : Convert.ToInt32(reader["ReferenceID"]),
                        Notes = reader["Notes"] == DBNull.Value ? string.Empty : reader["Notes"].ToString(),
                        IsAutoGenerated = reader["IsAutoGenerated"] != DBNull.Value && Convert.ToBoolean(reader["IsAutoGenerated"]),
                        CreatedAt = reader["CreatedAt"] == DBNull.Value ? DateTime.MinValue : Convert.ToDateTime(reader["CreatedAt"])
                    };
                }
            }
        }

